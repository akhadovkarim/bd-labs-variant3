-- 2. Путь каждого курсанта: автошкола, группа, категория, результат
SELECT CONCAT(k.familiya, ' ', k.imya) AS kursant,
       a.nazvanie AS avtoshkola, g.nomer_gruppy, kp.kod AS kategoriya,
       IF(vu.id IS NULL, 'ещё не получено', vu.seriya_nomer) AS voditelskoe_udostoverenie
  FROM kursant k
  JOIN dogovor d           ON d.kursant_id = k.id
  JOIN uchebnaya_gruppa g  ON g.id = d.gruppa_id
  JOIN avtoshkola a        ON a.id = g.avtoshkola_id
  JOIN kategoriya_prav kp  ON kp.id = g.kategoriya_id
  LEFT JOIN voditelskoe_udostoverenie vu ON vu.kursant_id = k.id
 ORDER BY k.familiya;

-- 3. Результаты экзаменов в Госавтоинспекции с числом попыток
SELECT CONCAT(k.familiya, ' ', k.imya) AS kursant, t.nazvanie AS ekzamen,
       e.nomer_popytki, e.rezultat, e.kol_oshibok,
       CONCAT(i.zvanie, ' ', i.familiya) AS inspektor
  FROM ekzamen e
  JOIN kursant k      ON k.id = e.kursant_id
  JOIN tip_ekzamena t ON t.id = e.tip_ekzamena_id
  LEFT JOIN inspektor i ON i.id = e.inspektor_id
 WHERE t.etap = 'gibdd'
 ORDER BY k.familiya, e.data_ekzamena;

-- 4. Задолженность по оплате обучения
SELECT d.nomer, CONCAT(k.familiya, ' ', k.imya) AS kursant, d.stoimost,
       COALESCE(SUM(o.summa), 0) AS oplacheno,
       d.stoimost - COALESCE(SUM(o.summa), 0) AS dolg
  FROM dogovor d
  JOIN kursant k ON k.id = d.kursant_id
  LEFT JOIN oplata_obucheniya o ON o.dogovor_id = d.id
 GROUP BY d.id, d.nomer, kursant, d.stoimost
HAVING dolg > 0;
